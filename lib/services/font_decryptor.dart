  /// 解密正文与章节内容反爬字符
  static String decryptText(String? text) {
    if (text == null || text.isEmpty) return '';
    final buffer = StringBuffer();
    for (int i = 0; i < text.length; i++) {
      final char = text[i];
      buffer.write(readerFontMap[char] ?? char);
    }
    return buffer.toString();
  }

  /// 解密书库与分类书籍列表反爬字符
  static String decryptLibText(String? text) {
    if (text == null || text.isEmpty) return '';
    final buffer = StringBuffer();
    for (int i = 0; i < text.length; i++) {
      final char = text[i];
      buffer.write(libFontMap[char] ?? char);
    }
    return buffer.toString();
  }

  /// 解密正文 HTML 并转换为纯文本段落（对齐 BeautifulSoup 解密逻辑）
  static String decryptHtmlToText(String? htmlContent) {
    if (htmlContent == null || htmlContent.isEmpty) return '';
    final decrypted = decryptText(htmlContent);
    final pRegex = RegExp(r'<p[^>]*>(.*?)</p>', caseSensitive: false, dotAll: true);
    final matches = pRegex.allMatches(decrypted);
    final paragraphs = <String>[];
    if (matches.isNotEmpty) {
      for (final m in matches) {
        final clean = _stripHtml(m.group(1) ?? '').trim();
        if (clean.isNotEmpty) {
          paragraphs.add(clean);
        }
      }
    } else {
      final cleanAll = _stripHtml(decrypted);
      for (final line in cleanAll.split('\n')) {
        final trimmed = line.trim();
        if (trimmed.isNotEmpty) {
          paragraphs.add(trimmed);
        }
      }
    }
    return paragraphs.join('\n\n');
  }

  static String _stripHtml(String html) {
    return html
        .replaceAll(RegExp(r'<br\s*/?>', caseSensitive: false), '\n')
        .replaceAll(RegExp(r'<[^>]*>'), '')
        .replaceAll('&nbsp;', ' ')
        .replaceAll('&amp;', '&')
        .replaceAll('&lt;', '<')
        .replaceAll('&gt;', '>')
        .replaceAll('&quot;', '"')
        .replaceAll('&#39;', "'");
  }

  /// 安全解析字数或章节数字符串
  static int parseIntSafe(dynamic val, [int defaultValue = 0]) {
    if (val == null) return defaultValue;
    if (val is int) return val;
    if (val is double) return val.toInt();
    try {
      final dec = decryptLibText(val.toString());
      if (dec.contains('万')) {
        final match = RegExp(r'(\d+(?:\.\d+)?)').firstMatch(dec);
        if (match != null) {
          final num = double.tryParse(match.group(1) ?? '');
          if (num != null) return (num * 10000).toInt();
        }
      }
      final digits = RegExp(r'\d+').allMatches(dec).map((m) => m.group(0)).join();
      if (digits.isNotEmpty) {
        return int.tryParse(digits) ?? defaultValue;
      }
    } catch (_) {}
    return defaultValue;
  }
